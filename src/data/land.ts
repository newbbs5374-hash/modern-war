function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 밑그림 → 자연스러운 해안선: 변마다 가운데점을 옆으로 흔들어(4번) 굴곡을 만들고 2번 둥글게 깎음 */
export function naturalOutline(
  base: Pt[],
  seed: number,
  rough = 0.22,
  depth = 4,
): Pt[] {
  const R = rng(seed);
  const out: Pt[] = [];
  for (let i = 0; i < base.length; i++) {
    let seg: Pt[] = [base[i], base[(i + 1) % base.length]];
    for (let d = 0; d < depth; d++) {
      const ns: Pt[] = [seg[0]];
      for (let j = 0; j < seg.length - 1; j++) {
        const [x0, y0] = seg[j];
        const [x1, y1] = seg[j + 1];
        const L = Math.hypot(x1 - x0, y1 - y0) || 1;
        const o = (R() * 2 - 1) * L * rough;
        ns.push(
          [
            (x0 + x1) / 2 + (-(y1 - y0) / L) * o,
            (y0 + y1) / 2 + ((x1 - x0) / L) * o,
          ],
          seg[j + 1],
        );
      }
      seg = ns;
    }
    out.push(...seg.slice(0, -1));
  }
  let p = out;
  for (let k = 0; k < 2; k++) {
    const q: Pt[] = [];
    for (let i = 0; i < p.length; i++) {
      const a = p[i];
      const b = p[(i + 1) % p.length];
      q.push(
        [a[0] * 0.75 + b[0] * 0.25, a[1] * 0.75 + b[1] * 0.25],
        [a[0] * 0.25 + b[0] * 0.75, a[1] * 0.25 + b[1] * 0.75],
      );
    }
    p = q;
  }
  return p;
}

/** 작은 섬 밑그림: 반지름 r 둥근 모양(조금 찌그러짐) */
export function blob(cx: number, cy: number, r: number, seed: number): Pt[] {
  const R = rng(seed * 7919 + 13);
  return Array.from({ length: 7 }, (_, i) => {
    const a = (i / 7) * Math.PI * 2;
    const rr = r * (0.8 + R() * 0.4) * (i % 2 ? 1.15 : 0.9);
    return [cx + Math.cos(a) * rr, cy + Math.sin(a) * rr * 0.85] as Pt;
  });
}

export function inPoly(x: number, y: number, p: Pt[]): boolean {
  let ins = false;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [xi, yi] = p[i];
    const [xj, yj] = p[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi)
      ins = !ins;
  }
  return ins;
}

