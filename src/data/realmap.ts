/** 경도·위도 → 지도 좌표(px) */
export function project(lon: number, lat: number): { x: number; y: number } {
  const l = lon < GEO.L0 ? lon + 360 : lon;
  return { x: (l - GEO.L0) * GEO.PX, y: (GEO.B1 - lat) * GEO.PX };
}

