/** 나라 특징 효과: 대통령실 효과와 같은 종류 + 자원 생산(res) */
export type NationEffKey = PostEff | 'res';
export interface NationTrait {
  icon: string;
  name: string;
  /** 쉬운 말 설명 */
  text: string;
  eff: Partial<Record<NationEffKey, number>>;
  /** 약점이면 true */
  weak?: boolean;
}

export interface NationGov {
  /** 지도자 집무실(대통령실 자리 이름) */
  office: string;
  /** 실 이름(비서실·정책실·국가안보실·경호처·청장·총리 묶음) */
  offices?: Partial<Record<OfficeId, string>>;
  ministries: Partial<Record<MinistryId, string>>;
  posts: Partial<Record<PostId, string>>;
  /** 시설 이름 [이름, 있는 도시 이름(그 나라 도시), 설명] — 도시가 없으면 차례로 둠 */
  facilities: Record<string, [string, string?, string?]>;
  /** 장군 자리 이름(합참·육군·해군·공군·정보·군수) */
  generals?: Partial<Record<'합참' | '육군' | '해군' | '공군' | '정보' | '군수', string>>;
  traits: NationTrait[];
  /** 한 줄 소개: 이 나라 내정은 어떤 맛인지 */
  style: string;
}

const T = (icon: string, name: string, text: string, eff: NationTrait['eff'], weak?: boolean): NationTrait => ({ icon, name, text, eff, ...(weak ? { weak } : {}) });

